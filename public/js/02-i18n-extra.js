function T(s){
  if (LANG !== 'en') return s;
  return Object.prototype.hasOwnProperty.call(I18N_EN, s) ? I18N_EN[s] : s;
}
function applyDir(){
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === 'en' ? 'ltr' : 'rtl';
  $('lang-switch').textContent = LANG === 'en' ? '🌐 العربية' : '🌐 English';
  document.title = T(document.title);
}
function translateStaticDOM(){
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = T(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = T(el.getAttribute('data-i18n-ph')); });
  document.querySelectorAll('[data-i18n-tip]').forEach(el => { el.setAttribute('data-tip', T(el.getAttribute('data-i18n-tip'))); });
}
function toggleLang(){
  LANG = LANG === 'ar' ? 'en' : 'ar';
  localStorage.setItem('azoom_lang', LANG);
  applyDir();
  translateStaticDOM();
  if (state) renderAll();
}

